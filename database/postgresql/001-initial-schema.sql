CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);
CREATE UNIQUE INDEX users_email_lower_unique ON users (lower(email));

CREATE TABLE sessions (
  session_id TEXT PRIMARY KEY,
  expires_at TIMESTAMPTZ NOT NULL,
  session_data JSONB NOT NULL
);
CREATE INDEX idx_sessions_expires_at ON sessions (expires_at);

CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  parent_id BIGINT REFERENCES categories(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  description TEXT NOT NULL DEFAULT '',
  image_url TEXT NOT NULL DEFAULT '',
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  display_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);
CREATE INDEX idx_categories_parent_active_order ON categories (parent_id, active, display_order);

CREATE TABLE sellers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
  store_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  gstin TEXT NOT NULL DEFAULT '',
  platform_owned SMALLINT NOT NULL DEFAULT 0 CHECK (platform_owned IN (0, 1)),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'rejected', 'suspended')),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  approved_at TEXT
);

CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  description TEXT NOT NULL,
  price_paise BIGINT NOT NULL CHECK (price_paise >= 0),
  image_url TEXT NOT NULL,
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  featured SMALLINT NOT NULL DEFAULT 0 CHECK (featured IN (0, 1)),
  seller_id BIGINT REFERENCES sellers(id) DEFERRABLE INITIALLY DEFERRED,
  category_id BIGINT REFERENCES categories(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
  sku TEXT
);
CREATE INDEX idx_products_category_id ON products (category_id);
CREATE UNIQUE INDEX idx_products_sku_unique ON products (sku) WHERE sku IS NOT NULL AND sku <> '';

CREATE TABLE product_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  image_url TEXT NOT NULL,
  model_profile TEXT NOT NULL DEFAULT 'general',
  view_label TEXT NOT NULL DEFAULT 'Other view',
  display_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  UNIQUE (product_id, image_url)
);
CREATE INDEX idx_product_images_product_order ON product_images (product_id, display_order, id);

CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
  total_paise BIGINT NOT NULL CHECK (total_paise >= 0),
  shipping_name TEXT NOT NULL,
  shipping_address TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'placed',
  payment_method TEXT NOT NULL DEFAULT 'cash_on_delivery',
  payment_status TEXT NOT NULL DEFAULT 'pending',
  razorpay_order_id TEXT,
  razorpay_payment_id TEXT,
  discount_paise BIGINT NOT NULL DEFAULT 0,
  coupon_code TEXT,
  tracking_carrier TEXT,
  tracking_code TEXT,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  product_id BIGINT NOT NULL REFERENCES products(id) DEFERRABLE INITIALLY DEFERRED,
  product_name TEXT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  price_paise BIGINT NOT NULL CHECK (price_paise >= 0),
  seller_id BIGINT REFERENCES sellers(id) DEFERRABLE INITIALLY DEFERRED,
  commission_paise BIGINT NOT NULL DEFAULT 0,
  seller_payout_paise BIGINT NOT NULL DEFAULT 0,
  discount_paise BIGINT NOT NULL DEFAULT 0,
  payout_status TEXT NOT NULL DEFAULT 'pending'
);

CREATE TABLE seller_fulfillments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  seller_id BIGINT NOT NULL REFERENCES sellers(id) DEFERRABLE INITIALLY DEFERRED,
  status TEXT NOT NULL DEFAULT 'placed' CHECK (status IN ('pending_payment', 'placed', 'processing', 'shipped', 'delivered', 'cancelled')),
  tracking_carrier TEXT,
  tracking_code TEXT,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  UNIQUE (order_id, seller_id)
);
CREATE INDEX idx_seller_fulfillments_seller_status ON seller_fulfillments (seller_id, status, order_id);

CREATE TABLE marketplace_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  commission_basis_points INTEGER NOT NULL DEFAULT 1000 CHECK (commission_basis_points BETWEEN 0 AND 5000)
);

CREATE TABLE seller_payouts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_id BIGINT NOT NULL REFERENCES sellers(id) DEFERRABLE INITIALLY DEFERRED,
  amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
  reference TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  paid_by_user_id BIGINT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE saved_addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  recipient_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  line1 TEXT NOT NULL,
  line2 TEXT NOT NULL DEFAULT '',
  city TEXT NOT NULL,
  state TEXT NOT NULL,
  postal_code TEXT NOT NULL,
  is_default SMALLINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE wishlists (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  PRIMARY KEY (user_id, product_id)
);

CREATE TABLE reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  order_id BIGINT NOT NULL REFERENCES orders(id) DEFERRABLE INITIALLY DEFERRED,
  rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body TEXT NOT NULL,
  image_mime TEXT,
  image_data TEXT,
  status TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('approved', 'hidden')),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  UNIQUE (user_id, product_id, order_id)
);

CREATE TABLE coupons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL,
  discount_basis_points INTEGER NOT NULL CHECK (discount_basis_points BETWEEN 1 AND 10000),
  min_order_paise BIGINT NOT NULL DEFAULT 0 CHECK (min_order_paise >= 0),
  max_discount_paise BIGINT,
  usage_limit INTEGER,
  usage_count INTEGER NOT NULL DEFAULT 0,
  expires_at TEXT,
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
);
CREATE UNIQUE INDEX coupons_code_lower_unique ON coupons (lower(code));

CREATE TABLE return_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) DEFERRABLE INITIALLY DEFERRED,
  user_id BIGINT NOT NULL REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
  reason TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'refunded')),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  resolved_at TEXT,
  resolved_by_user_id BIGINT REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED
);
