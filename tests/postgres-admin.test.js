const assert = require("node:assert/strict");
const test = require("node:test");
const { PGlite } = require("@electric-sql/pglite");
const createPostgresAdminRepository = require("../src/repositories/postgres-admin.repository");

test("PostgreSQL admin repository manages categories and coupons", async () => {
  const postgres = new PGlite();
  await postgres.exec(`
    CREATE TABLE categories (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT, slug TEXT, parent_id INTEGER, description TEXT, image_url TEXT, active INTEGER DEFAULT 1, display_order INTEGER DEFAULT 0, updated_at TIMESTAMP);
    CREATE TABLE products (id INTEGER PRIMARY KEY, category_id INTEGER, sku TEXT);
    CREATE TABLE coupons (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT, discount_basis_points INTEGER, min_order_paise INTEGER, max_discount_paise INTEGER, usage_limit INTEGER, expires_at TEXT, active INTEGER DEFAULT 1);
  `);
  const repository = createPostgresAdminRepository(postgres);
  const category = await repository.createCategory({ name: "Electronics", slug: "electronics", parentId: null, description: "Devices", imageUrl: "", active: 1, displayOrder: 0 });
  assert.equal(category.slug, "electronics");
  assert.equal(await repository.categorySlugExists("electronics"), true);
  const coupon = await repository.createCoupon({ code: "SAVE10", discountBasisPoints: 1000, minOrderPaise: 0, maxDiscountPaise: null, usageLimit: null, expiresAt: null });
  assert.equal(coupon.code, "SAVE10");
});
