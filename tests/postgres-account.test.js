const assert = require("node:assert/strict");
const test = require("node:test");
const { PGlite } = require("@electric-sql/pglite");
const createPostgresAccountRepository = require("../src/repositories/postgres-account.repository");

test("PostgreSQL account repository manages addresses and wishlists", async () => {
  const postgres = new PGlite();
  await postgres.exec(`
    CREATE TABLE users (id INTEGER PRIMARY KEY, password_hash TEXT);
    CREATE TABLE saved_addresses (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL, recipient_name TEXT, phone TEXT, line1 TEXT, line2 TEXT,
      city TEXT, state TEXT, postal_code TEXT, is_default BOOLEAN NOT NULL DEFAULT false
    );
    CREATE TABLE categories (id INTEGER PRIMARY KEY, active BOOLEAN NOT NULL);
    CREATE TABLE sellers (id INTEGER PRIMARY KEY, store_name TEXT, status TEXT);
    CREATE TABLE products (id INTEGER PRIMARY KEY, seller_id INTEGER, category_id INTEGER, name TEXT,
      category TEXT, price_paise INTEGER, image_url TEXT, stock INTEGER);
    CREATE TABLE wishlists (user_id INTEGER, product_id INTEGER, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (user_id, product_id));
  `);
  await postgres.query("INSERT INTO users (id, password_hash) VALUES (1,'hash')");
  await postgres.query("INSERT INTO sellers VALUES (1,'Test Seller','active')");
  await postgres.query("INSERT INTO categories VALUES (1,true)");
  await postgres.query("INSERT INTO products VALUES (1,1,1,'Product','General',1000,'x',5)");

  const repository = createPostgresAccountRepository(postgres);
  const address = { recipientName: "Test User", phone: "9876543210", line1: "Main Road", line2: "", city: "Delhi", state: "Delhi", postalCode: "110001" };
  const created = await repository.createAddress(1, address, true);
  assert.equal(created.isDefault, 1);
  assert.equal((await repository.listAddresses(1))[0].recipientName, "Test User");

  await repository.addToWishlist(1, 1);
  await repository.addToWishlist(1, 1);
  assert.equal((await repository.listWishlist(1)).length, 1);
  await repository.removeFromWishlist(1, 1);
  assert.equal((await repository.listWishlist(1)).length, 0);
  assert.equal((await repository.findPasswordHash(1)).password_hash, "hash");
});
