const assert = require("node:assert/strict");
const test = require("node:test");
const { PGlite } = require("@electric-sql/pglite");
const createPostgresOrdersRepository = require("../src/repositories/postgres-orders.repository");

test("PostgreSQL orders repository quotes, reserves stock, and cancels COD orders", async () => {
  const postgres = new PGlite();
  await postgres.exec(`
    CREATE TABLE sellers (id INTEGER PRIMARY KEY, status TEXT);
    CREATE TABLE categories (id INTEGER PRIMARY KEY, active INTEGER);
    CREATE TABLE products (id INTEGER PRIMARY KEY, name TEXT, price_paise INTEGER, stock INTEGER, seller_id INTEGER, category_id INTEGER, platform_owned INTEGER DEFAULT 0);
    CREATE TABLE marketplace_settings (id INTEGER PRIMARY KEY, commission_basis_points INTEGER);
    CREATE TABLE coupons (id INTEGER PRIMARY KEY, code TEXT, discount_basis_points INTEGER, min_order_paise INTEGER, max_discount_paise INTEGER, usage_limit INTEGER, usage_count INTEGER DEFAULT 0, expires_at TEXT, active INTEGER DEFAULT 1);
    CREATE TABLE orders (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER, total_paise INTEGER, shipping_name TEXT, shipping_address TEXT, status TEXT, payment_method TEXT, payment_status TEXT, razorpay_order_id TEXT, razorpay_payment_id TEXT, discount_paise INTEGER DEFAULT 0, coupon_code TEXT);
    CREATE TABLE order_items (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER, product_id INTEGER, product_name TEXT, quantity INTEGER, price_paise INTEGER, seller_id INTEGER, commission_paise INTEGER, seller_payout_paise INTEGER, discount_paise INTEGER);
    CREATE TABLE inventory_movements (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id INTEGER, order_id INTEGER, movement_type TEXT, quantity INTEGER);
    CREATE TABLE seller_fulfillments (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER, seller_id INTEGER, status TEXT, updated_at TIMESTAMP);
    CREATE TABLE return_requests (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER, user_id INTEGER, reason TEXT);
    CREATE TABLE payment_events (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, provider TEXT, provider_event_id TEXT UNIQUE, provider_order_id TEXT, provider_payment_id TEXT, event_type TEXT, payload JSONB);
    CREATE TABLE payment_refunds (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, provider TEXT, provider_refund_id TEXT UNIQUE, provider_payment_id TEXT, order_id INTEGER, amount_paise INTEGER, currency TEXT, status TEXT);
    INSERT INTO sellers VALUES (1, 'active');
    INSERT INTO categories VALUES (1, 1);
    INSERT INTO products VALUES (1, 'Test Phone', 10000, 5, 1, 1, 0);
    INSERT INTO marketplace_settings VALUES (1, 1000);
  `);
  const repository = createPostgresOrdersRepository(postgres);
  const quote = await repository.calculateCartQuote(new Map([[1, 2]]));
  assert.equal(quote.totalPaise, 20000);

  const order = await repository.saveOrder({
    userId: 7, quantities: new Map([[1, 2]]), couponCode: "",
    shippingName: "Test Customer", shippingAddress: "Test Address",
    paymentMethod: "cash_on_delivery", paymentStatus: "pending"
  });
  assert.equal(order.totalPaise, 20000);

  const stock = await postgres.query("SELECT stock FROM products WHERE id=1");
  assert.equal(Number(stock.rows[0].stock), 3);
  const movements = await postgres.query("SELECT movement_type, quantity FROM inventory_movements WHERE order_id=$1", [order.id]);
  assert.equal(movements.rows[0].movement_type, "reserve");
  assert.equal(Number(movements.rows[0].quantity), 2);

  await repository.cancelCustomerOrder(order.id, 7);
  const cancelled = await postgres.query("SELECT status,payment_status FROM orders WHERE id=$1", [order.id]);
  assert.equal(cancelled.rows[0].status, "cancelled");
  const restoredStock = await postgres.query("SELECT stock FROM products WHERE id=1");
  assert.equal(Number(restoredStock.rows[0].stock), 5);
});
