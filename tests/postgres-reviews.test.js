const assert = require("node:assert/strict");
const test = require("node:test");
const { PGlite } = require("@electric-sql/pglite");
const createPostgresReviewsRepository = require("../src/repositories/postgres-reviews.repository");

test("PostgreSQL reviews repository lists, creates, and moderates reviews", async () => {
  const postgres = new PGlite();
  await postgres.exec(`
    CREATE TABLE users (id INTEGER PRIMARY KEY, name TEXT);
    CREATE TABLE products (id INTEGER PRIMARY KEY, name TEXT);
    CREATE TABLE orders (id INTEGER PRIMARY KEY, user_id INTEGER, status TEXT);
    CREATE TABLE order_items (order_id INTEGER, product_id INTEGER);
    CREATE TABLE reviews (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER, product_id INTEGER, order_id INTEGER, rating INTEGER, body TEXT, image_mime TEXT, image_data BYTEA, status TEXT DEFAULT 'pending', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
    INSERT INTO users VALUES (1, 'Customer');
    INSERT INTO products VALUES (1, 'Phone');
    INSERT INTO orders VALUES (1, 1, 'delivered');
    INSERT INTO order_items VALUES (1, 1);
  `);
  const repository = createPostgresReviewsRepository(postgres);
  const purchase = await repository.findReviewablePurchase(1, 1);
  assert.equal(Number(purchase.orderId), 1);
  const created = await repository.createReview({ userId: 1, productId: 1, orderId: 1, rating: 5, body: "Excellent" });
  assert.equal(Number(created.lastInsertRowid), 1);
  await repository.moderateReview(1, "approved");
  const reviews = await repository.listProductReviews(1);
  assert.equal(reviews.length, 1);
  assert.equal(reviews[0].body, "Excellent");
});
