const assert = require("node:assert/strict");
const test = require("node:test");
const { PGlite } = require("@electric-sql/pglite");
const createPostgresSellerRepository = require("../src/repositories/postgres-seller.repository");

test("PostgreSQL seller repository manages applications and products", async () => {
  const postgres = new PGlite();
  await postgres.exec(`
    CREATE TABLE sellers (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER, store_name TEXT, phone TEXT, gstin TEXT, status TEXT, approved_at TIMESTAMP, platform_owned INTEGER DEFAULT 0);
    CREATE TABLE products (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT, sku TEXT, category TEXT, category_id INTEGER, description TEXT, price_paise INTEGER, image_url TEXT, stock INTEGER, featured INTEGER, seller_id INTEGER);
    CREATE TABLE product_images (id INTEGER PRIMARY KEY, product_id INTEGER, image_url TEXT, model_profile TEXT, view_label TEXT, display_order INTEGER);
    CREATE TABLE orders (id INTEGER PRIMARY KEY, total_paise INTEGER, shipping_name TEXT, shipping_address TEXT, status TEXT, payment_method TEXT, payment_status TEXT, created_at TIMESTAMP);
    CREATE TABLE seller_fulfillments (order_id INTEGER, seller_id INTEGER, status TEXT, tracking_carrier TEXT, tracking_code TEXT);
    CREATE TABLE order_items (product_id INTEGER, product_name TEXT, quantity INTEGER, price_paise INTEGER, seller_payout_paise INTEGER, payout_status TEXT, order_id INTEGER, seller_id INTEGER);
    CREATE TABLE marketplace_settings (id INTEGER PRIMARY KEY, commission_basis_points INTEGER);
    CREATE TABLE seller_payouts (id INTEGER PRIMARY KEY, seller_id INTEGER, amount_paise INTEGER, reference TEXT, notes TEXT, created_at TIMESTAMP);
    INSERT INTO marketplace_settings VALUES (1, 100);
  `);
  const repository = createPostgresSellerRepository(postgres);
  const application = await repository.submitApplication(7, { storeName: "Test Store", phone: "9876543210", gstin: "" });
  assert.equal(application.statusCode, 201);
  const seller = await repository.findSellerByUserId(7);
  assert.equal(seller.storeName, "Test Store");
  const product = await repository.saveSellerProduct(seller.id, { name: "Phone", sku: "P1", category: "Electronics", categoryId: 1, description: "Phone", pricePaise: 1000, imageUrl: "phone.jpg", stock: 5 });
  assert.equal(product.name, "Phone");
  assert.equal(await repository.deleteSellerProduct(seller.id, product.id), "deleted");
});
